import { build } from 'esbuild';
import { fileURLToPath } from 'node:url';
import { readFileSync, writeFileSync } from 'node:fs';
const source = fileURLToPath(new URL('../browser/data/passwordPage.ts', import.meta.url));
const output = fileURLToPath(new URL('../browser/data/passwordPageSource.ts', import.meta.url));
const result = await build({ entryPoints: [source], bundle: true, write: false, format: 'iife',
  absWorkingDir: fileURLToPath(new URL('../', import.meta.url)),
  globalName: 'RemoteAIBrowserPassword', target: 'es2020', legalComments: 'none' });
const generated = '// Generated by shared/scripts/build-browser-password.mjs. Do not edit.\n'
  + `export const passwordPageSource = ${JSON.stringify(result.outputFiles[0].text)};\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) throw new Error('Browser password source needs regeneration');
} else writeFileSync(output, generated);
